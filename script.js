const otdrSelect = document.getElementById("calc-otdr");
const outInstallation = document.getElementById("out-installation");
const outSplices = document.getElementById("out-splices");
const outPomiary = document.getElementById("out-pomiary");
const outTotal = document.getElementById("out-total");

function updateRangeTrack() {
	const min = +rangeInput.min,
		max = +rangeInput.max,
		val = +rangeInput.value;
	rangeInput.style.setProperty(
		"--pct",
		((val - min) / (max - min)) * 100 + "%",
	);
}

function calculateCosts() {
	const cur = CURRENCY[currentLang];
	const distance = parseInt(rangeInput.value) || 0;
	const costPerMeter = parseFloat(typeSelect.value) || 0;
	const splicesCount = parseInt(splicesInput.value) || 0;
	const isOtdr = otdrSelect.value === "yes";

	rangeVal.textContent = distance + " m";
	updateRangeTrack();

	const installPLN = distance * costPerMeter;
	const splicesPLN = splicesCount * cur.spliceUnit;
	const otdrPLN = isOtdr
		? splicesCount * cur.otdrPerSplice + cur.otdrBase
		: 0;
	const totalPLN = installPLN + splicesPLN + otdrPLN;

	const toDisplay = (n) => n / cur.rate;
	const fmt = (n) =>
		new Intl.NumberFormat(cur.locale, {
			style: "currency",
			currency: cur.code,
			maximumFractionDigits: 2,
		}).format(n);

	outInstallation.textContent = fmt(toDisplay(installPLN));
	outSplices.textContent = fmt(toDisplay(splicesPLN));
	outPomiary.textContent = fmt(toDisplay(otdrPLN));
	outTotal.textContent = fmt(toDisplay(totalPLN));
}

rangeInput.addEventListener("input", calculateCosts);
typeSelect.addEventListener("change", calculateCosts);
splicesInput.addEventListener("input", calculateCosts);
otdrSelect.addEventListener("change", calculateCosts);
calculateCosts();
